def _toml_value_to_text(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, np.integer)):
        return str(int(value))
    if isinstance(value, (float, np.floating)):
        val = float(value)
        if not np.isfinite(val):
            raise ValueError(f"Cannot serialize non-finite float to TOML: {val}")
        return f"{val:.12g}"
    if isinstance(value, str):
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        return f'"{escaped}"'
    if isinstance(value, list):
        return "[" + ", ".join(_toml_value_to_text(v) for v in value) + "]"
    raise TypeError(f"Unsupported TOML value type: {type(value)!r}")


def _toml_dict_to_lines(data: dict, section: tuple[str, ...] = ()) -> list[str]:
    lines: list[str] = []
    scalar_items: list[tuple[str, object]] = []
    child_items: list[tuple[str, dict]] = []
    for key, value in data.items():
        if isinstance(value, dict):
            child_items.append((key, value))
        else:
            scalar_items.append((key, value))

    if section:
        lines.append(f"[{'.'.join(section)}]")
    for key, value in scalar_items:
        lines.append(f"{key} = {_toml_value_to_text(value)}")
    if scalar_items and child_items:
        lines.append("")

    for idx, (key, child) in enumerate(child_items):
        lines.extend(_toml_dict_to_lines(child, section=section + (key,)))
        if idx < len(child_items) - 1:
            lines.append("")
    return lines


def _write_toml(path: Path, data: dict, comments: list[str] | None = None) -> None:
    lines = _toml_dict_to_lines(data)
    if comments:
        header = [f"# {line}" for line in comments]
        lines = header + [""] + lines
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")


def _load_run_wdm_nli_simulation(nli_script_path: Path):
    module_name = "gnlse_examples_nli_runtime"
    module_dir = str(nli_script_path.parent)
    if module_dir not in sys.path:
        sys.path.insert(0, module_dir)
    spec = importlib.util.spec_from_file_location(module_name, nli_script_path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Unable to import module from {nli_script_path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    run_fn = getattr(module, "run_wdm_nli_simulation", None)
    if run_fn is None:
        raise AttributeError(f"run_wdm_nli_simulation not found in {nli_script_path}")
    return run_fn


def _safe_loss_db_per_m(system: System, channel_idx: int) -> float:
    freqs = system.wdm.frequency_grid()
    center_freq = float(freqs[channel_idx])
    center_wl = c0 / center_freq
    loss_profile = getattr(system.fiber, "loss_profile", None)
    if callable(loss_profile):
        loss = np.asarray(loss_profile(np.array([center_wl], dtype=float)), dtype=float).reshape(-1)
        if loss.size:
            return float(loss[0])
    losses = getattr(system.fiber, "losses", None)
    if losses is not None:
        vals = np.asarray(losses, dtype=float).reshape(-1)
        if vals.size:
            return float(vals[-1])
    return 0.0


def _safe_beta2_ps2_per_m(system: System, channel_idx: int) -> float:
    freqs = system.wdm.frequency_grid()
    try:
        _, beta2_grid = system.beta_grids(freqs)
        beta2_val = float(np.asarray(beta2_grid, dtype=float)[0, channel_idx])
    except Exception:
        beta2_val = float(getattr(system.fiber, "beta2", 0.0) or 0.0)
    return beta2_val * 1e24


def _compute_min_samples_per_symbol_for_nyquist(
    *,
    symbol_rate_gbd: float,
    channel_spacing_thz: float,
    n_channels: int,
    pulse_shape: str,
    rrc_rolloff: float,
) -> int:
    symbol_rate_thz = float(symbol_rate_gbd) * 1e-3
    if symbol_rate_thz <= 0.0:
        raise ValueError("symbol_rate_gbd must be positive")
    max_offset_thz = channel_spacing_thz * (n_channels - 1) / 2.0
    if pulse_shape == "rrc":
        effective_bw_factor = 1.0 + float(rrc_rolloff)
    else:
        effective_bw_factor = 1.0

    rhs = (2.0 * max_offset_thz / symbol_rate_thz) + effective_bw_factor
    sps = int(np.ceil(rhs))
    return max(sps, 2)


def _build_ssfm_runtime_config(
    *,
    template_cfg: dict,
    system: System,
    baud_rate_hz: float,
    launch_channel_w: float,
    channel_idx: int,
    out_dir: Path,
    baud_tag: str,
) -> dict:
    cfg = copy.deepcopy(template_cfg)

    mod = cfg.setdefault("modulation", {})
    pulse_shape = str(mod.get("pulse_shape", "nyquist_rect"))
    rrc_rolloff = float(mod.get("rrc_rolloff", 0.0))
    mod["symbol_rate_gbd"] = float(baud_rate_hz * 1e-9)

    wdm = cfg.setdefault("wdm", {})
    wdm["n_channels"] = 5
    spacing = float(system.channel_spacing) if system.channel_spacing is not None else float(np.mean(np.diff(system.wdm.frequency_grid())))
    wdm["channel_spacing_thz"] = float(spacing * 1e-12)
    wdm["power_per_channel_w"] = float(launch_channel_w)

    mod["samples_per_symbol"] = _compute_min_samples_per_symbol_for_nyquist(
        symbol_rate_gbd=float(mod["symbol_rate_gbd"]),
        channel_spacing_thz=float(wdm["channel_spacing_thz"]),
        n_channels=int(wdm["n_channels"]),
        pulse_shape=pulse_shape,
        rrc_rolloff=rrc_rolloff,
    )

    freqs = system.wdm.frequency_grid()
    center_freq = float(freqs[channel_idx])
    fiber = cfg.setdefault("fiber", {})
    fiber["wavelength_nm"] = float((c0 / center_freq) * 1e9)
    fiber["fiber_length_m"] = float(system.fiber_length)
    fiber["nonlinearity"] = float(getattr(system.fiber, "gamma", 1.3e-3))
    fiber["loss_db_per_m"] = 0.0
    fiber["betas"] = [float(_safe_beta2_ps2_per_m(system, channel_idx))]

    output = cfg.setdefault("output", {})
    output["save_dir"] = str(out_dir / "ssfm")
    output["save_name"] = f"ssfm_constellation_{baud_tag}.png"
    output["show_plot"] = False

    cache = cfg.setdefault("cache", {})
    cache.setdefault("mode", "recompute")

    return cfg


def _extract_ssfm_center_nli_w(payload: dict) -> float | None:
    try:
        value = payload["power_report"]["center_channel"]["nli_power_avg_w"]
        if value is None:
            return None
        out = float(value)
        if not np.isfinite(out):
            return None
        return out
    except Exception:
        return None


def _prepare_ssfm_runtime(out_dir: Path) -> dict | None:
    nli_script_path = Path(
        str(Path.home() / "sw" / "gnlse-python" / "examples" / "nli" / "nli.py")
    )
    cfg_template_path = Path(
        str(Path.home() / "sw" / "gnlse-python" / "input" / "wdm_nli_config.toml")
    )
    if not nli_script_path.exists():
        nli_script_path = _DEFAULT_GNLSE_NLI_PY
    if not cfg_template_path.exists():
        cfg_template_path = _DEFAULT_GNLSE_WDM_CONFIG

    if not nli_script_path.exists() or not cfg_template_path.exists():
        lg.warning(
            "SSFM disabled: missing gnlse resources. script={}, template={}",
            nli_script_path,
            cfg_template_path,
        )
        return None

    try:
        run_fn = _load_run_wdm_nli_simulation(nli_script_path)
        template_cfg = _toml_load(cfg_template_path)
        if not isinstance(template_cfg, dict):
            raise TypeError("Template TOML root is not a mapping")
    except Exception as exc:
        lg.warning("SSFM disabled: could not initialize gnlse runner ({})", exc)
        return None

    runtime_toml_path = Path(__file__).resolve().parents[1] / "input" / _SSFM_RUNTIME_TOML_NAME
    lg.info(
        "SSFM enabled via gnlse: script={}, template={}, runtime_toml={}",
        nli_script_path,
        cfg_template_path,
        runtime_toml_path,
    )
    return {
        "run_fn": run_fn,
        "template_cfg": template_cfg,
        "runtime_toml_path": runtime_toml_path,
        "out_dir": out_dir,
    }


