def run_baud_sweep(
    cfg_path: Path,
    baud_rates_gbaud: list[float],
    out_dir: Path,
    launch_dbm: float | None,
    pcfm_numeric_xci: bool | None,
    pcfm_eq18_xci: bool | None,
    recompute_td: bool | None,
    recompute_pcfm: bool | None,
    exclude_self_channel: bool | None = None,
    run_ssfm_when_standalone: bool = False,
) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    rows: list[dict] = []

    base_system = System.from_toml(cfg_path)
    runtime_cfg = _load_pcfm_runtime_config(base_system)
    run_flags = _resolve_scaling_run_flags(
        base_system,
        pcfm_numeric_xci=pcfm_numeric_xci,
        pcfm_eq18_xci=pcfm_eq18_xci,
        recompute_td=recompute_td,
        recompute_pcfm=recompute_pcfm,
        exclude_self_channel=exclude_self_channel,
    )
    pcfm_numeric_xci = run_flags["pcfm_numeric_xci"]
    pcfm_eq18_xci = run_flags["pcfm_eq18_xci"]
    recompute_td = run_flags["recompute_td"]
    recompute_pcfm = run_flags["recompute_pcfm"]
    exclude_self_channel = run_flags["exclude_self_channel"]
    plot_pcfm_total_and_sci = bool(runtime_cfg["plot_pcfm_total_and_sci"])
    center_idx, band_label = _select_scaling_channel(base_system)
    freqs = base_system.wdm.frequency_grid()
    channel_freq_thz = float(freqs[center_idx] * 1e-12)
    if launch_dbm is not None:
        title_launch_vec = np.full(base_system.n_channels, float(dBm2watt(launch_dbm)), dtype=float)
    else:
        title_launch_vec = _build_constant_launch_vector(base_system, None)
    lg.info(
        "Selected center channel idx={} in band={} at {:.6f} THz.".format(
            center_idx, band_label, channel_freq_thz
        )
    )

    ssfm_ctx = _prepare_ssfm_runtime(out_dir) if run_ssfm_when_standalone else None

    for baud_gbaud in baud_rates_gbaud:
        system = System.from_toml(cfg_path)
        baud_hz = float(baud_gbaud) * 1e9
        _set_baud_rate(system, baud_hz)
        launch_vec = _build_constant_launch_vector(system, launch_dbm)

        baud_tag = f"R{_safe_tag(baud_gbaud)}GBd"
        profile_path = out_dir / f"flat_profile_{baud_tag}.npy"
        _write_flat_profile(profile_path, system, launch_powers_w=launch_vec)
        profile_power_tag = _power_profile_hash(system, profile_path)
        cache_tag = f"{baud_tag}_prof{profile_power_tag}"
        output_over_launch_signal_power_ratio = _output_over_launch_signal_power_ratio(
            system=system,
            profile_path=profile_path,
            launch_powers_w=launch_vec,
        )

        ccfs = collision_coeffs_system_uwb(
            system,
            ipulse=1,
            recompute=recompute_td,
            profile_path=profile_path,
        )
        td_tag = f"{cache_tag}_{'xci' if exclude_self_channel else 'all'}"
        td_cache = _nlin_cache_path(
            profile_path=profile_path,
            use_kappa=True,
            use_x_mode=True,
            extra_tag=td_tag,
        )
        nlin_td = total_nlin_uwb(
            system,
            ccfs,
            use_kappa=True,
            use_x_mode=True,
            launch_powers_w=launch_vec,
            exclude_self_channel=exclude_self_channel,
            cache_path=td_cache,
            recompute=recompute_td,
        )
        td_vec = _launch_referenced_nlin_to_output_power(
            nlin_td,
            output_over_launch_signal_power_ratio,
        )

        const_pref, sum_a, sum_b = _td_modulation_components(
            system,
            ccfs,
            launch_vec,
            use_kappa=True,
            use_x_mode=True,
            exclude_self_channel=exclude_self_channel,
        )
        td_gaussian_vec = _launch_referenced_nlin_to_output_power(
            np.asarray(
                const_pref * (gaussian_mu0() * sum_a + sum_b),
                dtype=float,
            ),
            output_over_launch_signal_power_ratio,
        )

        pcfm_cfg = PcfmConfig(
            degree=9,
            include_mci=False,
            use_numeric_sci=True,
            use_numeric_xci=bool(pcfm_numeric_xci),
        )
        pcfm_path = out_dir / f"pcfm_{cache_tag}.npy"
        pcfm_total, pcfm_sci, pcfm_xci = _load_or_compute_pcfm_I(
            system=system,
            profile_path=profile_path,
            launch_powers_w=launch_vec,
            output_path=pcfm_path,
            cfg=pcfm_cfg,
            recompute=recompute_pcfm,
            return_components=True,
        )
        pcfm_total = _launch_referenced_nlin_to_output_power(
            pcfm_total,
            output_over_launch_signal_power_ratio,
        )
        pcfm_sci = _launch_referenced_nlin_to_output_power(
            pcfm_sci,
            output_over_launch_signal_power_ratio,
        )
        pcfm_xci = _launch_referenced_nlin_to_output_power(
            pcfm_xci,
            output_over_launch_signal_power_ratio,
        )

        row = {
            "baud_rate_gbaud": float(baud_gbaud),
            "channel_idx": int(center_idx),
            "band_label": band_label,
            "channel_freq_thz": channel_freq_thz,
            "launch_channel_w": float(launch_vec[center_idx]),
            "td_channel_w": float(td_vec[center_idx]),
            "td_gaussian_channel_w": float(td_gaussian_vec[center_idx]),
            "pcfm_channel_w": float(pcfm_total[center_idx]),
            "pcfm_sci_channel_w": float(pcfm_sci[center_idx]),
            "pcfm_xci_channel_w": float(pcfm_xci[center_idx]),
            "analytic_limit_channel_w": _center_channel_analytic_limit(
                system, float(launch_vec[center_idx]), center_idx
            ) * float(output_over_launch_signal_power_ratio[center_idx]),
        }
        if ssfm_ctx is not None:
            try:
                ssfm_val = _compute_ssfm_center_nli(
                    ssfm_ctx,
                    system=system,
                    baud_rate_hz=baud_hz,
                    launch_channel_w=float(launch_vec[center_idx]),
                    channel_idx=center_idx,
                    baud_tag=baud_tag,
                )
                if ssfm_val is not None:
                    row["ssfm_channel_w"] = float(ssfm_val)
                else:
                    lg.warning("SSFM returned no finite center-channel NLI for {}", baud_tag)
            except Exception as exc:
                lg.warning("SSFM run failed for {}: {}", baud_tag, exc)
        if pcfm_eq18_xci:
            row["pcfm_eq18_xci_channel_w"] = _center_channel_eq18_xci(
                system, float(launch_vec[center_idx]), center_idx
            ) * float(output_over_launch_signal_power_ratio[center_idx])
        rows.append(row)
        msg = (
            "R={:.1f} GBd -> TD={:.3e} W, TD(Gauss)={:.3e} W, PCFM={:.3e} W, "
            "PCFM_SCI={:.3e} W, PCFM_XCI={:.3e} W, Analytic={:.3e} W"
        ).format(
            row["baud_rate_gbaud"],
            row["td_channel_w"],
            row["td_gaussian_channel_w"],
            row["pcfm_channel_w"],
            row["pcfm_sci_channel_w"],
            row["pcfm_xci_channel_w"],
            row["analytic_limit_channel_w"],
        )
        if pcfm_eq18_xci:
            msg += ", PCFM_XCI_Eq18={:.3e} W".format(row["pcfm_eq18_xci_channel_w"])
        if "ssfm_channel_w" in row:
            msg += ", SSFM={:.3e} W".format(row["ssfm_channel_w"])
        lg.info(msg)


    rows.sort(key=lambda item: item["baud_rate_gbaud"])
    baud_rates_hz = np.array([row["baud_rate_gbaud"] * 1e9 for row in rows], dtype=float)
    for key in (
        "td_channel_w",
        "td_gaussian_channel_w",
        "pcfm_channel_w",
        "pcfm_sci_channel_w",
        "pcfm_xci_channel_w",
        "analytic_limit_channel_w",
    ):
        exponent = _fit_exponent(baud_rates_hz, np.array([row[key] for row in rows], dtype=float))
        for row in rows:
            row[f"{key}_scaling_exp"] = exponent
    if any("ssfm_channel_w" in row for row in rows):
        exponent = _fit_exponent(baud_rates_hz, np.array([row.get("ssfm_channel_w", np.nan) for row in rows], dtype=float))
        for row in rows:
            if "ssfm_channel_w" in row:
                row["ssfm_channel_w_scaling_exp"] = exponent
    if pcfm_eq18_xci:
        exponent = _fit_exponent(baud_rates_hz, np.array([row["pcfm_eq18_xci_channel_w"] for row in rows], dtype=float))
        for row in rows:
            row["pcfm_eq18_xci_channel_w_scaling_exp"] = exponent

    csv_path = out_dir / "center_channel_baud_scaling.csv"
    header = [
        "baud_rate_gbaud",
        "channel_idx",
        "band_label",
        "channel_freq_thz",
        "launch_channel_w",
        "td_channel_w",
        "td_gaussian_channel_w",
        "pcfm_channel_w",
        "pcfm_sci_channel_w",
        "pcfm_xci_channel_w",
        "analytic_limit_channel_w",
        "td_channel_w_scaling_exp",
        "td_gaussian_channel_w_scaling_exp",
        "pcfm_channel_w_scaling_exp",
        "pcfm_sci_channel_w_scaling_exp",
        "pcfm_xci_channel_w_scaling_exp",
        "analytic_limit_channel_w_scaling_exp",
    ]
    if any("ssfm_channel_w" in row for row in rows):
        header.extend([
            "ssfm_channel_w",
            "ssfm_channel_w_scaling_exp",
        ])
    if pcfm_eq18_xci:
        header.extend([
            "pcfm_eq18_xci_channel_w",
            "pcfm_eq18_xci_channel_w_scaling_exp",
        ])
    data = np.column_stack([[row.get(name, np.nan) for row in rows] for name in header])
    np.savetxt(csv_path, data, delimiter=",", header=",".join(header), comments="", fmt="%s")

    plot_path = Path("media") / "PCFM" / "center_channel_baud_scaling.pdf"
    _plot_scaling(
        rows,
        plot_path,
        base_system,
        center_idx,
        band_label,
        channel_freq_thz,
        title_launch_vec,
        plot_pcfm_total_and_sci=plot_pcfm_total_and_sci,
    )

    summary_lines = [
        f"Center channel idx={center_idx}, band={band_label}, freq={channel_freq_thz:.6f} THz",
        f"TD mode: {'exclude self-channel (nuB==nuA)' if exclude_self_channel else 'include all channels'}",
        f"TD 64-QAM exponent: {_fit_exponent(baud_rates_hz, np.array([row['td_channel_w'] for row in rows], dtype=float)):.6f}",
        f"TD Gaussian exponent: {_fit_exponent(baud_rates_hz, np.array([row['td_gaussian_channel_w'] for row in rows], dtype=float)):.6f}",
        f"PCFM total exponent: {_fit_exponent(baud_rates_hz, np.array([row['pcfm_channel_w'] for row in rows], dtype=float)):.6f}",
        f"PCFM SCI exponent: {_fit_exponent(baud_rates_hz, np.array([row['pcfm_sci_channel_w'] for row in rows], dtype=float)):.6f}",
        f"PCFM XCI exponent: {_fit_exponent(baud_rates_hz, np.array([row['pcfm_xci_channel_w'] for row in rows], dtype=float)):.6f}",
        f"Analytic limit exponent: {_fit_exponent(baud_rates_hz, np.array([row['analytic_limit_channel_w'] for row in rows], dtype=float)):.6f}",
    ]
    if any("ssfm_channel_w" in row for row in rows):
        summary_lines.append(
            f"SSFM exponent: {_fit_exponent(baud_rates_hz, np.array([row.get('ssfm_channel_w', np.nan) for row in rows], dtype=float)):.6f}"
        )
    if pcfm_eq18_xci:
        summary_lines.append(
            f"PCFM XCI Eq18 exponent: {_fit_exponent(baud_rates_hz, np.array([row['pcfm_eq18_xci_channel_w'] for row in rows], dtype=float)):.6f}"
        )
    summary_path = out_dir / "center_channel_baud_scaling_summary.txt"
    summary_path.write_text("\n".join(summary_lines) + "\n")
    return csv_path, summary_path


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Sweep baud rate and inspect center-channel TD/PCFM scaling."
    )
    parser.add_argument(
        "--config",
        type=str,
        default="input/pcfm_struct.toml",
        help="Path to system TOML.",
    )
    parser.add_argument(
        "--baud-rates-gbaud",
        type=str,
        default=None,
        help=(
            "Optional comma-separated baud rates in GBaud. "
            "If omitted, uses geometric spacing from --baud-min-gbaud to --baud-max-gbaud."
        ),
    )
    parser.add_argument(
        "--baud-min-gbaud",
        type=float,
        default=10.0,
        help="Minimum baud rate in GBaud for geometric sweep.",
    )
    parser.add_argument(
        "--baud-max-gbaud",
        type=float,
        default=100.0,
        help="Maximum baud rate in GBaud for geometric sweep.",
    )
    parser.add_argument(
        "--baud-npoints",
        type=int,
        default=5,
        help="Number of points for geometric baud-rate sweep.",
    )
    parser.add_argument(
        "--launch-dbm",
        type=float,
        default=None,
        help="Optional uniform launch power override in dBm.",
    )
    parser.add_argument(
        "--pcfm-numeric-xci",
        action=argparse.BooleanOptionalAction,
        default=None,
        help="Override [pcfm.run].pcfm_numeric_xci.",
    )
    parser.add_argument(
        "--recompute-td",
        action=argparse.BooleanOptionalAction,
        default=None,
        help="Override [pcfm.run].td_mode.",
    )
    parser.add_argument(
        "--recompute-pcfm",
        action=argparse.BooleanOptionalAction,
        default=None,
        help="Override [pcfm.run].pcfm_mode.",
    )
    parser.add_argument(
        "--exclude-self-channel",
        action=argparse.BooleanOptionalAction,
        default=None,
        help="Override [pcfm.run].td_exclude_self_channel.",
    )
    parser.add_argument(
        "--out-dir",
        type=str,
        default="results/debug/pcfm_baud_scaling",
        help="Output directory for generated profiles, caches, and reports.",
    )
    args = parser.parse_args()

    if args.baud_rates_gbaud is not None:
        baud_rates_gbaud = _parse_float_list(args.baud_rates_gbaud)
    else:
        baud_rates_gbaud = _geometric_baud_rates(
            min_gbaud=float(args.baud_min_gbaud),
            max_gbaud=float(args.baud_max_gbaud),
            n_points=int(args.baud_npoints),
        )
    lg.info("Baud sweep [GBaud]: {}", ", ".join(f"{x:.6g}" for x in baud_rates_gbaud))

    csv_path, summary_path = run_baud_sweep(
        cfg_path=Path(args.config),
        baud_rates_gbaud=baud_rates_gbaud,
        out_dir=Path(args.out_dir),
        launch_dbm=args.launch_dbm,
        pcfm_numeric_xci=args.pcfm_numeric_xci,
        pcfm_eq18_xci=None,
        recompute_td=args.recompute_td,
        recompute_pcfm=args.recompute_pcfm,
        exclude_self_channel=args.exclude_self_channel,
        run_ssfm_when_standalone=True,
    )
    lg.success(f"Saved scaling CSV to {csv_path}")
    lg.success(f"Saved scaling summary to {summary_path}")


if __name__ == "__main__":
    main()
